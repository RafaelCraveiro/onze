/* O Supabase expõe as tabelas de "public" pela sua API REST. Este jogo só acede
   pelo servidor, por isso ativa-se RLS sem políticas: a API pública não lê nem
   escreve nada (contas e hashes incluídos); o servidor, dono das tabelas, continua. */
await db.exec(["users", "sessions", "saves", "club", "players", "market", "meta", "world_clock", "cups", "cup_entrants", "cup_matches", "cup_regs", "leagues", "league_clubs", "league_fixtures", "league_memo"]
  .map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join("\n"));

const hashPass = (password, salt) => crypto.scryptSync(password, salt, 64).toString("hex");
const newToken = () => crypto.randomBytes(32).toString("hex");
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

export const app = express();
app.use(express.json({ limit: "2mb" }));

/* Cada pedido corre numa transação, um de cada vez (ver server/db.mjs). A resposta
   só sai depois do COMMIT; se algo falhar, o pedido inteiro é desfeito. */
app.use("/api", (req, res, next) => {
  const sendJson = res.json.bind(res);
  db.tx(() => new Promise((resolve, reject) => {
    res.json = (body) => { resolve(body); return res; };
    req.failTx = reject;
    (async () => { const t = Date.now(); await club.ageWorldIfDue(t); await league.tickLeague(t); })().then(() => next(), reject);
  })).then(sendJson, (err) => {
    console.error("[api]", req.method, req.path, err);
    res.status(500);
    sendJson({ error: "erro-servidor" });
  });
});

/* middleware de autenticação por token (Authorization: Bearer …) */
const auth = async (req, res, next) => {
  const token = (req.headers.authorization ?? "").replace(/^Bearer\s+/i, "");
  if (!token) return res.status(401).json({ error: "sem-sessao" });
  const row = await db.prepare("SELECT user_id FROM sessions WHERE token = ?").get(token);
  if (!row) return res.status(401).json({ error: "sessao-invalida" });
  req.userId = row.user_id;
  req.token = token;
  next();
};

/* devolve {error} do club.mjs como resposta HTTP 400, ou aplica res.json(out) */
const reply = (res, out) => (out?.error ? res.status(400).json(out) : res.json(out ?? { ok: true }));

/* ---------- registo: email único + nome de clube único ---------- */
app.post("/api/register", async (req, res) => {
  const email = String(req.body?.email ?? "").trim().toLowerCase();
  const password = String(req.body?.password ?? "");
  const clubName = String(req.body?.clubName ?? "").trim();
  const emblem = req.body?.emblem;

  if (!EMAIL_RE.test(email)) return res.status(400).json({ error: "email-invalido" });
  if (password.length < 6) return res.status(400).json({ error: "password-curta" });
  if (clubName.length < 3 || clubName.length > 26) return res.status(400).json({ error: "clube-invalido" });
  if (!emblem || typeof emblem !== "object") return res.status(400).json({ error: "emblema-invalido" });

  if (await db.prepare("SELECT id FROM users WHERE email = ?").get(email))
    return res.status(409).json({ error: "email-existe" });
  if (await db.prepare("SELECT id FROM users WHERE LOWER(club_name) = LOWER(?)").get(clubName))
    return res.status(409).json({ error: "clube-existe" });

  const salt = crypto.randomBytes(16).toString("hex");
  const info = await db.prepare(
    "INSERT INTO users (email, pass_hash, pass_salt, club_name, emblem, created_at) VALUES (?, ?, ?, ?, ?, ?) RETURNING id"
  ).get(email, hashPass(password, salt), salt, clubName, JSON.stringify(emblem), Date.now());

  const token = newToken();
  const userId = info.id;
  await db.prepare("INSERT INTO sessions (token, user_id, created_at) VALUES (?, ?, ?)").run(token, userId, Date.now());
  const game = await club.tickClub(userId, Date.now());
  res.json({ token, clubName, email, game });
});

/* ---------- login ---------- */
app.post("/api/login", async (req, res) => {
  const email = String(req.body?.email ?? "").trim().toLowerCase();
  const password = String(req.body?.password ?? "");
  const user = await db.prepare("SELECT * FROM users WHERE email = ?").get(email);
  if (!user || hashPass(password, user.pass_salt) !== user.pass_hash)
    return res.status(401).json({ error: "credenciais" });

  const token = newToken();
  await db.prepare("INSERT INTO sessions (token, user_id, created_at) VALUES (?, ?, ?)").run(token, user.id, Date.now());
  const game = await club.tickClub(user.id, Date.now());
  res.json({ token, clubName: user.club_name, email: user.email, emblem: JSON.parse(user.emblem), game });
});

